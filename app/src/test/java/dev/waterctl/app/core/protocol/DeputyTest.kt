package dev.waterctl.app.core.protocol

import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * 全部期望值都来自原项目 waterctl 自己的测试文件（`solvers.spec.ts` / `algorithms.spec.ts`）。
 *
 * 其中密钥向量不是直接给出的：原测试断言的是 `makeUnlockResponse` 的完整输出，
 * 而输出里的 4 字节密钥 = `makeKey(...) ^ (设备名后 4 位数字)`。这里把掩码异或回去，
 * 就得到了 `makeKey` 的输入输出对 —— 等于拿原版的端到端测试来锁定本移植版本。
 */
class DeputyTest {

    private fun bytes(vararg v: Int) = ByteArray(v.size) { v[it].toByte() }

    private fun hex(b: ByteArray) = b.joinToString("") { "%02x".format(it.toInt() and 0xFF) }

    // ---------- makeKey ----------

    @Test
    fun `makeKey 与原项目端到端向量一致`() {
        val cases = listOf(
            // 输入 (nonceHi, nonceLo, macHi, macLo) -> 期望 rawKey
            intArrayOf(0x00, 0x05, 0x95, 0x27) to bytes(0xC0, 0x59, 0x92, 0xC6),
            intArrayOf(0x9B, 0x05, 0x95, 0x27) to bytes(0xF2, 0x39, 0x92, 0xD1),
            intArrayOf(0xFF, 0xFF, 0x95, 0x27) to bytes(0xD5, 0xA5, 0x37, 0x39),
            intArrayOf(0x34, 0x64, 0x80, 0x14) to bytes(0xD5, 0x21, 0x92, 0xC3),
            intArrayOf(0x81, 0xFF, 0x68, 0x30) to bytes(0xF2, 0x1B, 0xBA, 0x23),
            intArrayOf(0x01, 0xFF, 0x73, 0x24) to bytes(0xCF, 0xC3, 0x92, 0x22),
        )
        for ((input, expected) in cases) {
            val actual = Deputy.makeKey(input[0], input[1], input[2], input[3])
            assertEquals(
                "makeKey(${input.joinToString { "%02x".format(it) }})",
                hex(expected),
                hex(actual),
            )
        }
    }

    // ---------- CRC ----------

    @Test
    fun `crc16changgong 与原项目向量一致`() {
        assertEquals(0xD015, Crc.changGong("11070"))
        assertEquals(0x21E2, Crc.changGong("25333"))
        assertEquals(0x9B39, Crc.changGong("33982"))
        assertEquals(0xE08B, Crc.changGong("45130"))
        assertEquals(0x8D97, Crc.changGong("50312"))
    }

    @Test
    fun `crc16cgaeaf 与原项目向量一致`() {
        assertEquals(
            0x38,
            Crc.cgAeAf(bytes(0x00, 0x00, 0x05, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12)),
        )
        assertEquals(
            0xA2,
            Crc.cgAeAf(bytes(0x00, 0x9B, 0x05, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12)),
        )
        assertEquals(
            0x9F,
            Crc.cgAeAf(bytes(0x00, 0xFF, 0xFF, 0x95, 0x27, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12)),
        )
        assertEquals(
            0x69,
            Crc.cgAeAf(bytes(0x00, 0x00, 0x01, 0xCF, 0x75, 0x31, 0xD4, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00)),
        )
    }

    // ---------- makeUnlockResponse ----------

    @Test
    fun `makeUnlockResponse 与原项目向量逐字节一致`() {
        val deviceName = "Water33982"
        val tail = intArrayOf(0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x10, 0x11, 0x12)

        fun request(vararg head: Int) = bytes(*(head + tail))

        val cases = listOf(
            request(0xFD, 0xFD, 0x09, 0xAE, 0x38, 0x00, 0x00, 0x05, 0x95, 0x27) to
                bytes(0xFE, 0xFE, 0x09, 0xAF, 0x72, 0x00, 0x00, 0x06, 0xC3, 0x50, 0x9A, 0xC4, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00),
            request(0xFD, 0xFD, 0x09, 0xAE, 0xA2, 0x00, 0x9B, 0x05, 0x95, 0x27) to
                bytes(0xFE, 0xFE, 0x09, 0xAF, 0x44, 0x00, 0x9B, 0x06, 0xF1, 0x30, 0x9A, 0xD3, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00),
            // 与上一条 nonce / MAC 相同、仅 unknownByte 不同 —— 校验和必须跟着变
            request(0xFD, 0xFD, 0x09, 0xAE, 0x5B, 0x39, 0x9B, 0x05, 0x95, 0x27) to
                bytes(0xFE, 0xFE, 0x09, 0xAF, 0xBD, 0x39, 0x9B, 0x06, 0xF1, 0x30, 0x9A, 0xD3, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00),
            // nonce = 0xFFFF 的回绕特例
            request(0xFD, 0xFD, 0x09, 0xAE, 0x9F, 0x00, 0xFF, 0xFF, 0x95, 0x27) to
                bytes(0xFE, 0xFE, 0x09, 0xAF, 0xD9, 0x00, 0x01, 0x00, 0xD6, 0xAC, 0x3F, 0x3B, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00),
            request(0xFD, 0xFD, 0x09, 0xAE, 0xB1, 0x00, 0x34, 0x64, 0x80, 0x14) to
                bytes(0xFE, 0xFE, 0x09, 0xAF, 0xB1, 0x00, 0x34, 0x65, 0xD6, 0x28, 0x9A, 0xC1, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00),
            request(0xFD, 0xFD, 0x09, 0xAE, 0x01, 0x00, 0x81, 0xFF, 0x68, 0x30) to
                bytes(0xFE, 0xFE, 0x09, 0xAF, 0x68, 0x00, 0x82, 0x00, 0xF1, 0x12, 0xB2, 0x21, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00),
            request(0xFD, 0xFD, 0x09, 0xAE, 0x4B, 0x00, 0x01, 0xFF, 0x73, 0x24) to
                bytes(0xFE, 0xFE, 0x09, 0xAF, 0x4B, 0x00, 0x02, 0x00, 0xCC, 0xCA, 0x9A, 0x20, 0xFE, 0x87, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00),
        )

        cases.forEachIndexed { index, (request, expected) ->
            val actual = Solvers.makeUnlockResponse(request, deviceName)
            assertArrayEquals("case #$index", expected, actual)
        }
    }

    // ---------- makeStartEpilogue ----------

    @Test
    fun `makeStartEpilogue 结构正确`() {
        val deviceName = "Water33982"

        val old = Solvers.makeStartEpilogue(deviceName, isKeyAuthPresent = false)
        assertEquals(20, old.size)
        assertArrayEquals(bytes(0xFE, 0xFE, 0x09, 0xB2, 0x01), old.copyOfRange(0, 5))
        val checksumOld = (old[5].toInt() and 0xFF) or ((old[6].toInt() and 0xFF) shl 8)
        assertEquals(Crc.changGong(deviceName.takeLast(5)), checksumOld)
        assertEquals(0xFF, old[7].toInt() and 0xFF)
        assertEquals(0x00, old[8].toInt() and 0xFF)
        assertEquals("0f2700", hex(old.copyOfRange(17, 20)))

        val new = Solvers.makeStartEpilogue(deviceName, isKeyAuthPresent = true)
        assertEquals(20, new.size)
        assertEquals(0x0B, new[7].toInt() and 0xFF)
        assertArrayEquals(old.copyOfRange(0, 7), new.copyOfRange(0, 7))
        assertArrayEquals(old.copyOfRange(8, 9), new.copyOfRange(8, 9))
        assertArrayEquals(old.copyOfRange(17, 20), new.copyOfRange(17, 20))
    }

    @Test
    fun `decAsHex 是 BCD 编码`() {
        // Byte.toInt() 会做符号扩展，所以统一 and 0xFF 取无符号值
        fun u(n: Int) = Solvers.decAsHex(n).toInt() and 0xFF
        assertEquals(0x00, u(0))
        assertEquals(0x42, u(42))
        assertEquals(0x26, u(2026 % 100))
        assertEquals(0x99, u(99))
    }
}
