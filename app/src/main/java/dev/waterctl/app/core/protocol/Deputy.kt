    private val TABLE: ByteArray = ByteArray(2096).also { out ->
        for (i in out.indices) {
            out[i] = ((Character.digit(TABLE_HEX[i * 2], 16) shl 4) or
                    Character.digit(TABLE_HEX[i * 2 + 1], 16)).toByte()
        }
    }

    private fun u(offset: Int): Int = TABLE[offset].toInt() and 0xFF

    /** a 的每个 bit 为 1 时异或的小常量，顺序对应 bit0..bit7。 */
    private val A_CONST = intArrayOf(1, 1, 2, 7, 1, 1, 1, 1)

    /**
     * `makeKey(a, b, c, d)`
     *
     * 调用方传入 `[nonce 高字节, nonce 低字节, MAC 高字节, MAC 低字节]`，返回 4 字节原始密钥。
     */
    fun makeKey(aIn: Int, bIn: Int, cIn: Int, dIn: Int): ByteArray {
        var a = aIn and 0xFF
        val b = bIn and 0xFF
        var c = cIn and 0xFF
        var d = dIn and 0xFF

        // 固件怪癖：b == 0xFF 且 a 为奇数时 a 需要 +2（再溢出回绕到 0）
        if (b == 0xFF && (a and 1) == 1) a += 2
        if (a == 257) a = 0

        // ---- iA ----
        var iA = d and 0x07
        val mA = d and 0xF8
        for (s in 3..7) if (mA and (1 shl s) != 0) iA = iA xor 4
        iA = iA xor u(0 + b)
        for (s in 0..7) if (a and (1 shl s) != 0) iA = iA xor A_CONST[s]

        // ---- iC ----
        var iC = c and 0x07
        val mC = c and 0xF8
        for (s in 3..7) if (mC and (1 shl s) != 0) iC = iC xor 4
        iC = iC xor u(768 + (b and 15))

        // ---- 派生 d、c 后再查表得到 iB、iD ----
        d = u(256 + b) xor d
        d = u(512 + a) xor d
        val iB = u(1296 + d)

        c = u(784 + b) xor c
        c = u(1040 + a) xor c
        val iD = u(1552 + c)

        // 原实现把结果写到内存偏移 2096..2099（小端），solvers.ts 读
        // Uint32Array[524] 后再按大端拆字节输出 —— 等价于下面这个顺序。
        return byteArrayOf(
            u(1938 + iA).toByte(),
            u(1808 + iB).toByte(),
            u(2082 + iC).toByte(),
            u(1952 + iD).toByte(),
        )
    }
